#!/usr/bin/env python3
"""Generate the winmm.dll proxy export stubs from the system winmm.dll.

Usage (WSL):
    python3 -I scripts/gen-winmm-proxy.py /mnt/c/Windows/System32/winmm.dll src/proxy

Writes:
    winmm.def           export table with the same names and ordinals
    winmm_stubs.asm     one `jmp [table+i*8]` stub per export (MASM, x64)
    winmm_exports.inc   C++ list of {ordinal, name} used to fill the table
"""
import pathlib
import re
import subprocess
import sys


def read_exports(dll):
    out = subprocess.run(["llvm-readobj", "--coff-exports", dll],
                         check=True, capture_output=True, text=True).stdout
    exports = []
    for block in re.findall(r"Export \{(.*?)\}", out, re.S):
        ordinal = int(re.search(r"Ordinal: (\d+)", block).group(1))
        name = re.search(r"Name: ?(.*)", block).group(1).strip()
        exports.append((ordinal, name))
    return sorted(exports)


def main():
    dll, out_dir = sys.argv[1], pathlib.Path(sys.argv[2])
    exports = read_exports(dll)

    def stub(ordinal):
        return f"modpacks_winmm_stub_{ordinal}"

    lines = ["LIBRARY winmm", "EXPORTS"]
    for ordinal, name in exports:
        if name:
            lines.append(f"    {name}={stub(ordinal)} @{ordinal}")
        else:
            lines.append(f"    ordinal{ordinal}={stub(ordinal)} @{ordinal} NONAME")
    (out_dir / "winmm.def").write_text("\n".join(lines) + "\n", newline="\r\n")

    asm = ["; Generated by scripts/gen-winmm-proxy.py. Do not edit.",
           "EXTERN modpacks_winmm_table:QWORD", "", ".code", ""]
    for index, (ordinal, _) in enumerate(exports):
        asm += [f"{stub(ordinal)} PROC",
                f"    jmp QWORD PTR [modpacks_winmm_table + {index * 8}]",
                f"{stub(ordinal)} ENDP", ""]
    asm.append("END")
    (out_dir / "winmm_stubs.asm").write_text("\n".join(asm) + "\n", newline="\r\n")

    inc = ["// Generated by scripts/gen-winmm-proxy.py. Do not edit."]
    for ordinal, name in exports:
        inc.append(f'{{{ordinal}, {"nullptr" if not name else chr(34) + name + chr(34)}}},')
    (out_dir / "winmm_exports.inc").write_text("\n".join(inc) + "\n", newline="\r\n")
    print(f"{len(exports)} exports")


if __name__ == "__main__":
    main()
